        static Dictionary<string, List<P>> map;

        static void A(string key, string text, Func<Fox, Fox, bool> when = null, float weight = 1f)
        {
            if (!map.TryGetValue(key, out var l)) map[key] = l = new List<P>();
            l.Add(new P { text = text, when = when, weight = when != null ? weight * 2.2f : weight });
        }

        static void Many(string key, params string[] texts) { foreach (var t in texts) A(key, t); }

        static readonly Regex Tok = new Regex(@"\{(o:)?([^{}|]*)\|([^{}|]*)\}");

        static string Fill(string t, Fox me, Fox other)
        {
            t = t.Replace("{name}", other != null ? other.foxName : "");
            t = t.Replace("{me}", me != null ? me.foxName : "");
            return Tok.Replace(t, m =>
            {
                var who = m.Groups[1].Success ? other : me;
                bool f = who != null && who.female;
                return f ? m.Groups[3].Value : m.Groups[2].Value;
            });
        }

        public static string Pick(string key, Fox me, Fox other, string fallback = null)
        {
            if (map == null) Build();
            if (!map.TryGetValue(key, out var l)) return fallback;
            var cands = new List<P>();
            float sum = 0;
            foreach (var p in l)
            {
                if (p.when != null)
                {
                    bool ok;
                    try { ok = p.when(me, other); } catch { ok = false; }
                    if (!ok) continue;
                }
                if (me != null && me.recentPhrases.Contains(p.text)) continue;
                cands.Add(p); sum += p.weight;
            }
            if (cands.Count == 0) { if (fallback != null) return Fill(fallback, me, other); if (l.Count == 0) return null; cands.Add(l[UnityEngine.Random.Range(0, l.Count)]); sum = cands[0].weight; }
            float r = UnityEngine.Random.value * sum;
            P pick = cands[cands.Count - 1];
            foreach (var p in cands) { r -= p.weight; if (r <= 0) { pick = p; break; } }
            if (me != null)
            {
                me.recentPhrases.Add(pick.text);
                if (me.recentPhrases.Count > 10) me.recentPhrases.RemoveAt(0);
            }
            return Fill(pick.text, me, other);
        }

